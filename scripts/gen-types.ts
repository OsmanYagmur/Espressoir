/**
 * Regenerates packages/db/src/database.types.ts.
 *   pnpm types:gen                     (from supabase/migrations, using an in-process Postgres:
 *                                       no Docker, no network, no secrets)
 *   pnpm types:gen --db-url <url>      (from a running database, e.g. the CI Supabase stack)
 */
import { execFile } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { promisify } from "node:util";

import { PGLiteSocketServer } from "@electric-sql/pglite-socket";

import { repoRoot } from "./lib/target-env";
import { applyMigrations, createEmbeddedPostgres } from "./lib/test-db";

const OUTPUT = resolve(repoRoot, "packages/db/src/database.types.ts");
const EMBEDDED_PORT = 54329;

const run = promisify(execFile);

async function generate(dbUrl: string): Promise<string> {
  // Async on purpose: the embedded database lives in this process and must stay responsive.
  const { stdout } = await run(
    "supabase",
    ["gen", "types", "typescript", "--db-url", dbUrl, "--schema", "public"],
    { cwd: repoRoot, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
  );
  if (!stdout.trim()) throw new Error("supabase gen types returned nothing.");
  return stdout;
}

async function generateFromMigrations(): Promise<string> {
  const db = await createEmbeddedPostgres();
  await applyMigrations(db);
  const server = new PGLiteSocketServer({ db, port: EMBEDDED_PORT, host: "127.0.0.1" });
  await server.start();
  try {
    return await generate(
      `postgresql://postgres:postgres@127.0.0.1:${EMBEDDED_PORT}/postgres?sslmode=disable`,
    );
  } finally {
    await server.stop();
    await db.close();
  }
}

const flagIndex = process.argv.indexOf("--db-url");
const dbUrl = flagIndex === -1 ? undefined : process.argv[flagIndex + 1];

try {
  const types = dbUrl ? await generate(dbUrl) : await generateFromMigrations();
  writeFileSync(OUTPUT, `// Generated by \`pnpm types:gen\`. Do not edit by hand.\n${types}`);
  await run("prettier", ["--write", OUTPUT], { cwd: repoRoot });
  console.log(`✓ ${OUTPUT.replace(`${repoRoot}/`, "")} güncellendi.`);
} catch (error) {
  console.error("Tip üretimi başarısız oldu.");
  console.error((error as { stderr?: string }).stderr ?? error);
  process.exit(1);
}
