/**
 * Regenerates packages/db/src/database.types.ts from the dev database schema.
 *   pnpm types:gen                     (uses SUPABASE_DB_URL from .env.local)
 *   pnpm types:gen --db-url <url>      (any database, e.g. the local CI stack)
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { assertTarget, loadTargetEnv, repoRoot, requireEnv } from "./lib/target-env";

const OUTPUT = resolve(repoRoot, "packages/db/src/database.types.ts");

const flagIndex = process.argv.indexOf("--db-url");
let dbUrl = flagIndex === -1 ? undefined : process.argv[flagIndex + 1];
if (!dbUrl) {
  loadTargetEnv("dev");
  dbUrl = requireEnv("SUPABASE_DB_URL");
  await assertTarget("dev", dbUrl);
}

const result = spawnSync(
  "supabase",
  ["gen", "types", "typescript", "--db-url", dbUrl, "--schema", "public"],
  { cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);
if (result.status !== 0 || !result.stdout.trim()) {
  console.error("Tip üretimi başarısız oldu.");
  process.exit(result.status ?? 1);
}

writeFileSync(OUTPUT, `// Generated by \`pnpm types:gen\`. Do not edit by hand.\n${result.stdout}`);
spawnSync("prettier", ["--write", OUTPUT], { cwd: repoRoot, stdio: "inherit" });
console.log(`✓ ${OUTPUT.replace(`${repoRoot}/`, "")} güncellendi.`);
